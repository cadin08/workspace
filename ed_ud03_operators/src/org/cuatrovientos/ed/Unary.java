package org.cuatrovientos.ed;

public class Unary {

	public static void main(String[] args) {
		
		int result = +1;
		System.out.println(result); // 1
		
		result--;
		System.out.println(result); //0
		
		result += 5; // 5
		
		System.out.println(++result);
		System.out.println(result++);
		
		
		
				
		
		
	}

}
