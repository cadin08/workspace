package org.cuatrovientos.ed;

public class AritmeticOperators {

	public static void main(String[] args) {
		
		int result = 1 + 2;
		System.out.println("1 + 2 ="+ result); // 3
		
		result = 1 - 2;
		System.out.println("1 - 2 ="+ result); // -1
		
		result = 1 * 2;
		System.out.println("1 * 2 ="+ result); // 2
		
		result = 1 / 2;
		System.out.println("1 / 2 ="+ result); // 0.5
											   // 0.5
		result = 1 % 2;
		System.out.println("1 % 2 ="+ result); // 1 (Resto de la division)
		
		

			

	}

}
